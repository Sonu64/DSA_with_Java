public class bitwiseOperators {
    public static void main(String[] args) {
        System.out.println("Bitwise AND - 5 & 6 = " + (5 & 6));
        System.out.println("Bitwise OR - 5 | 6 = " + (5 | 6));
        System.out.println("Bitwise NOT (Binary 1's complement) of 5, ~5 = " + (~5));
        System.out.println("Left Shifting 5 by 2 bits, 5 << 2 = " + (5 << 2));
        System.out.println("Right Shifting 5 by 2 bits, 5 >> 2 = " + (5 >> 2));
    }
}
